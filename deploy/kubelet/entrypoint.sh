#!/bin/sh
# kubelet entrypoint.
#
# The kubelet dials pod IPs directly for liveness/readiness/startup probes
# (httpGet/tcpSocket) and for HTTP lifecycle hooks (postStart/preStop). In the
# multi-container compose stack every pod runs inside the shared `containerd`
# CRI service's CNI bridge (pod CIDR 10.244.0.0/16 on cni0) — a different
# network namespace from this kubelet container. With no route to that CIDR the
# probe/hook dial fails, the kubelet marks the container unhealthy and restarts
# it in a loop, and probe/lifecycle-hook NodeConformance specs fail.
#
# Install a route to the pod CIDR via the containerd container, mirroring the
# api-server entrypoint (and the node route a real cluster's CNI / route
# controller programs for the pod network). Best-effort: never block startup —
# on stacks without a separate containerd service (all-in-one) it is simply
# skipped.
POD_CIDR="${POD_CIDR:-10.244.0.0/16}"
POD_NET_GW="${POD_NET_GW:-}"
if [ -z "$POD_NET_GW" ]; then
    # The containerd CRI service owns the pod network; resolve it via compose DNS.
    POD_NET_GW="$(getent hosts containerd 2>/dev/null | awk '{ print $1; exit }')"
fi
if [ -n "$POD_NET_GW" ]; then
    if ip route replace "$POD_CIDR" via "$POD_NET_GW" 2>/dev/null; then
        echo "kubelet entrypoint: routed pod CIDR $POD_CIDR via $POD_NET_GW (containerd) for probes/lifecycle hooks"
    else
        echo "kubelet entrypoint: WARNING: could not add route $POD_CIDR via $POD_NET_GW (need cap_add NET_ADMIN / privileged?); probes and HTTP lifecycle hooks to pod IPs may fail" >&2
    fi
else
    echo "kubelet entrypoint: note: no 'containerd' host to route pod CIDR via; skipping pod-network route (expected on all-in-one / non-CRI stacks)"
fi

# Pods with dnsPolicy Default (and CoreDNS's `forward . /etc/resolv.conf`) take
# their upstream resolvers from the kubelet's --resolv-conf. In a docker/compose
# container /etc/resolv.conf is docker's embedded resolver, 127.0.0.11, which in
# a POD's network namespace is the pod's own loopback: CoreDNS forwards to
# itself, the `loop` plugin detects it and exits, and cluster DNS crash-loops.
# k3s handles exactly this in pkg/agent/config/config.go
# (locateOrGenerateResolvConf / isValidResolvConf / isValidNameserver): use
# /etc/resolv.conf only if every nameserver is a global unicast address,
# otherwise generate "nameserver 8.8.8.8 / 2001:4860:4860::8888" and point the
# kubelet at that. Same here; an explicit --resolv-conf is left alone.
valid_resolv_conf() {
    [ -r "$1" ] || return 1
    awk '
        $1 == "nameserver" {
            ns = tolower($2); found = 1
            # loopback, unspecified, link-local (except the instance metadata
            # service IP, which upstream allows), multicast
            if (ns == "169.254.169.254") next
            if (ns ~ /^127\./ || ns ~ /^0\./ || ns ~ /^169\.254\./ || ns ~ /^(22[4-9]|23[0-9])\./ \
                || ns == "255.255.255.255" || ns == "::1" || ns == "::" || ns ~ /^fe[89ab]/ || ns ~ /^ff/) bad = 1
        }
        END { exit (found && !bad) ? 0 : 1 }' "$1"
}
RESOLV_ARGS=""
case " $* " in
    *" --resolv-conf"*) ;;
    *)
        if ! valid_resolv_conf /etc/resolv.conf; then
            mkdir -p /run/k3rs
            printf 'nameserver 8.8.8.8\nnameserver 2001:4860:4860::8888\n' > /run/k3rs/resolv.conf
            RESOLV_ARGS="--resolv-conf /run/k3rs/resolv.conf"
            echo "kubelet entrypoint: WARNING: /etc/resolv.conf includes loopback, multicast, or link-local nameservers - kubelet will use autogenerated resolv.conf with nameservers 8.8.8.8 2001:4860:4860::8888" >&2
        fi
        ;;
esac

# shellcheck disable=SC2086
exec /app/kubelet "$@" $RESOLV_ARGS
