#!/usr/bin/env python3
"""Generate crates/api-server/src/deprecation/table.rs from the Kubernetes
checkout's staging/src/k8s.io/api/*/*/zz_generated.prerelease-lifecycle.go
(prerelease-lifecycle-gen output: APILifecycleDeprecated / Removed /
Replacement). Group names come from each version's register.go GroupName.

usage: gen_deprecation_table.py <k8s-checkout> <sha>   > table.rs
"""
import glob
import os
import re
import sys

k8s, sha = sys.argv[1], sys.argv[2]
api = os.path.join(k8s, "staging/src/k8s.io/api")
fn_re = re.compile(
    r"func \(in \*(\w+)\) APILifecycle(Deprecated|Removed|Replacement)\(\)[^{]*\{\s*return ([^\n]+)\n"
)
gvk_re = re.compile(r'Group: "([^"]*)", Version: "([^"]*)", Kind: "([^"]*)"')
entries = []
for path in sorted(glob.glob(api + "/*/*/zz_generated.prerelease-lifecycle.go")):
    ver = path.split("/")[-2]
    reg = os.path.join(os.path.dirname(path), "register.go")
    group = re.search(r'const GroupName = "([^"]*)"', open(reg).read()).group(1)
    per = {}
    for kind, what, ret in fn_re.findall(open(path).read()):
        d = per.setdefault(kind, {})
        if what == "Replacement":
            d[what] = gvk_re.search(ret).groups()
        else:
            a, b = ret.split(",")
            d[what] = (int(a), int(b))
    for kind, d in per.items():
        if "Deprecated" in d:
            entries.append((group, ver, kind, d))
entries.sort(key=lambda e: (e[0], e[1], e[2]))

out = [
    "//! Generated by scripts/gen_deprecation_table.py from release-1.35",
    f"//! (kubernetes commit {sha})",
    "//! staging/src/k8s.io/api/*/*/zz_generated.prerelease-lifecycle.go.",
    "//! Do not edit by hand.",
    "",
    "use super::Lifecycle;",
    "",
    "pub const TABLE: &[Lifecycle] = &[",
]
for g, v, k, d in entries:
    dep = d["Deprecated"]
    rem = d.get("Removed")
    rep = d.get("Replacement")
    removed = f"Some(({rem[0]}, {rem[1]}))" if rem else "None"
    replacement = f'Some(("{rep[0]}", "{rep[1]}", "{rep[2]}"))' if rep else "None"
    out.append(
        f'    Lifecycle {{ group: "{g}", version: "{v}", kind: "{k}", '
        f"deprecated: ({dep[0]}, {dep[1]}), removed: {removed}, replacement: {replacement} }},"
    )
out.append("];")
print("\n".join(out))
