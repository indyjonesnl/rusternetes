#!/usr/bin/env python3
"""Render the dump of upstream's versioned feature gates (JSON on stdin, see
scripts/feature-gates/dump.go.txt) as crates/common/src/feature_gates/upstream_table.rs.

usage: gen_feature_gate_table.py <upstream-commit-sha> < gates.json > upstream_table.rs
"""
import json
import re
import sys

PRE = {
    "": "Ga",
    "ALPHA": "Alpha",
    "BETA": "Beta",
    "DEPRECATED": "Deprecated",
}


def main() -> None:
    sha = sys.argv[1]
    gates = json.load(sys.stdin)
    # AllAlpha / AllBeta are the specials `NewVersionedFeatureGate` seeds into
    # `known` (feature_gate.go:305-318); rusternetes handles them in
    # resolve_gates, not as table rows.
    gates = [g for g in gates if g["name"] not in ("AllAlpha", "AllBeta")]
    out = []
    w = out.append
    w("// @generated by scripts/gen-feature-gate-table.sh -- DO NOT EDIT.")
    w("//")
    w("// Every versioned feature gate (and dependency edge) that kube-apiserver")
    w("// registers on `utilfeature.DefaultMutableFeatureGate`, dumped from")
    w(f"// Kubernetes release-1.35 @ {sha} via `GetAllVersioned()` /")
    w("// `Dependencies()`: `defaultVersionedKubernetesFeatureGates` in")
    w("// pkg/features/kube_features.go, staging/src/k8s.io/apiserver/pkg/features/kube_features.go,")
    w("// staging/src/k8s.io/apiextensions-apiserver/pkg/features/kube_features.go,")
    w("// staging/src/k8s.io/component-base/{zpages,logs/api/v1,metrics}/features/kube_features.go,")
    w("// staging/src/k8s.io/controller-manager/pkg/features/kube_features.go and")
    w("// staging/src/k8s.io/client-go/features/known_features.go, plus")
    w("// `defaultKubernetesFeatureGateDependencies` (pkg/features/kube_features.go).")
    w("// AllAlpha / AllBeta are the featuregate specials and are not rows here.")
    w("")
    w("use super::{spec, PreRelease, UpstreamGate};")
    w("")
    w("pub const UPSTREAM_GATES: &[UpstreamGate] = &[")
    for g in gates:
        assert re.fullmatch(r"[A-Za-z0-9]+", g["name"]), g["name"]
        rows = []
        for s in g["specs"]:
            major, minor = s["version"].split(".")
            assert major == "1", (g["name"], s)
            assert not s.get("min_compat"), (g["name"], s)
            rows.append(
                "spec({minor}, {d}, PreRelease::{p}, {l})".format(
                    minor=int(minor),
                    d=str(s["default"]).lower(),
                    p=PRE[s["pre"]],
                    l=str(s["lock"]).lower(),
                )
            )
        deps = ", ".join('"%s"' % d for d in (g["deps"] or []))
        w("    UpstreamGate {")
        w('        name: "%s",' % g["name"])
        w("        specs: &[%s]," % ", ".join(rows))
        w("        deps: &[%s]," % deps)
        w("    },")
    w("];")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
