fn scope(state: &ApiServerState, subresource: Option<&'static str>) -> RequestScope<Ingress> {
    let store = match subresource {
        Some(_) => crate::registry::networking::ingress::new_status_store(state.storage.clone()),
        None => crate::registry::networking::ingress::new_store(state.storage.clone()),
    };
    RequestScope {
        kind: GroupVersionKind {
            group: "networking.k8s.io".to_string(),
            version: "v1".to_string(),
            kind: "Ingress".to_string(),
        },
        resource: GroupVersionResource {
            group: "networking.k8s.io".to_string(),
            version: "v1".to_string(),
            resource: "ingresses".to_string(),
        },
        subresource,
        store: Box::new(store),
        apply: Some(crate::ssa::apply_legacy::<Ingress>),
        convert_to_internal: None,
        patch_conversion: None,
    }
}
fn patch_content_type(headers: &HeaderMap) -> &str {
    headers
        .get("x-original-content-type")
        .or_else(|| headers.get(axum::http::header::CONTENT_TYPE))
        .and_then(|v| v.to_str().ok())
        .unwrap_or("")
}

